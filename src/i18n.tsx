function detectSystem(): Lang {
  if (typeof navigator === "undefined") return "en";
  const tag = (navigator.language || "").toLowerCase();
  return tag.startsWith("zh") ? "zh" : "en";
}

function readStored(): Lang | null {
  if (typeof localStorage === "undefined") return null;
  const v = localStorage.getItem(STORAGE_KEY);
  return v === "en" || v === "zh" ? v : null;
}

type Vars = Record<string, string | number>;
type TFn = (key: string, vars?: Vars) => string;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
}

const I18nContext = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => readStored() ?? detectSystem());

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const value = useMemo<I18nCtx>(() => {
    const dict = DICTS[lang];
    const t: TFn = (key, vars) => {
      let s = dict[key] ?? key;
      if (vars) {
        for (const k of Object.keys(vars)) {
          s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(vars[k]));
        }
        if (Object.prototype.hasOwnProperty.call(vars, "count")) {
          s = s.replace(/\{s\}/g, Number(vars.count) <= 1 ? "" : "s");
        }
      }
      return s;
    };
    return { lang, setLang, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nCtx {
  const v = useContext(I18nContext);
  if (!v) throw new Error("useI18n must be used inside I18nProvider");
  return v;
}

export function useT(): TFn {
  return useI18n().t;
}

export function localeTag(lang: Lang): string {
  return lang === "zh" ? "zh-CN" : "en-US";
}
